      <section id="custom-blocks">
        <h2>カスタムブロック</h2>
        <p>
          HTMLや定型コンテンツを<strong>部品化</strong>し、複数の固定ページから参照します。同じヘッダー・フッター・注釈・キャンペーンバナーを何度も貼り付けずに済みます。
        </p>

        <h3 id="custom-blocks-basics">基本の使い方</h3>
        <ol>
          <li>
            サイドバー「カスタムブロック」→ <strong>新規</strong>で、ブロック名・HTML・（任意で）CSSを登録して保存します。
          </li>
          <li>
            固定ページの編集画面「ブロック」タブで、<strong>カスタムブロック</strong>を追加し、登録した部品を選びます。
          </li>
          <li>
            部品側を更新すると、それを参照している<strong>すべてのページ</strong>に反映されます（キャッシュにより反映が遅れる場合があります）。
          </li>
        </ol>
        <ul>
          <li>
            <strong>一覧</strong>: 各ブロックが何ページで使われているか件数表示されます。0件なら削除候補です。
          </li>
          <li>
            <strong>削除</strong>: 使用中のページがあると公開レイアウトが崩れるため、先にページ側のブロックを外してください。
          </li>
        </ul>

        <h3 id="custom-blocks-compare">比較と変更履歴</h3>
        <p>編集画面でも、固定ページと同様に差分確認と履歴が使えます。</p>
        <ul>
          <li>
            <strong>変更を比較</strong>: ヘッダーのボタンからモーダルを開き、<strong>見た目</strong>（PC/SP・差分ハイライト）と<strong>ソース</strong>（HTML/CSSなどのテキスト差分）を切り替えられます。
          </li>
          <li>
            <strong>変更履歴</strong>: 直近20件。比較・復元が可能です。更新保存のたびに、保存直前の内容が履歴に残ります。
          </li>
        </ul>
        <p>大きなHTMLを直す前に「変更を比較」で確認し、問題があれば履歴から復元する流れが安全です。</p>
      </section>


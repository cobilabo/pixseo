      <section id="preview-url">
        <h2>プレビューURLと本番の違い</h2>
        <p>
          公開サイトには<strong>プレビュー用のホスト名</strong>と、<strong>本番の独自ドメイン</strong>（カスタムドメイン接続時）の二系統があり、挙動が異なります。管理画面の「サイトを別タブで開く」などのリンクは、設定に応じてプレビュー用URL（
          <code>*.pixseo-preview.cloud</code>）を指すことがあります。
        </p>

        <h3 id="preview-url-basics">URLと役割</h3>
        <ul>
          <li>
            <strong>プレビュー用URL</strong>: 一般的に{' '}
            <code>https://（サービスのスラッグ）.pixseo-preview.cloud/</code> の形式です。言語プレフィックス付きのパス（例:{' '}
            <code>/ja/articles/記事スラッグ/</code>）で記事や固定ページを開けます。
          </li>
          <li>
            <strong>本番URL</strong>: カスタムドメインを有効にしている場合は、そのドメイン（<code>https://www.example.com/</code> など）が本番の公開面になります。どちらのURLで確認するかで、後述の「検索」「キャッシュ」「未公開記事の見え方」が変わります。
          </li>
          <li>
            プレビュー画面では、画面上に<strong>プレビュー表示用のバッジ</strong>などが出る場合があります（本番では出ません）。
          </li>
        </ul>

        <h3 id="preview-url-access-seo">アクセス制御と検索</h3>
        <p>
          <strong>ベーシック認証（プレビュー）</strong>:{' '}
          <code>*.pixseo-preview.cloud</code> へのアクセス時、サービス側でプレビュー用の認証が有効になっている場合、ブラウザのユーザー名・パスワード入力が求められます。認証が<strong>無効</strong>のときは、URLを知っていれば原則誰でも閲覧できるため、公開前の下書きを含むURLの取り扱いには注意してください。
        </p>
        <p>
          <strong>検索エンジン（Google など）</strong>: プレビュー用ホストでは、システム側の仕様として<strong>検索結果にインデックスされない（noindex 相当）</strong>扱いになります。管理画面「サイト」の「インデックス」トグルは、<strong>本番ドメインでサイトを表示したとき</strong>に検索エンジンへ載せるかどうかに効きます。プレビューURLでは、そのトグルの設定にかかわらず検索結果には載りません。
        </p>

        <h3 id="preview-url-content">表示されるコンテンツ</h3>
        <ul>
          <li>
            <strong>本番ドメイン</strong>: 記事の一覧・詳細では、原則<strong>公開済み</strong>の記事だけが対象です。公開日時が未来の予約投稿は、公開日時まで一覧・詳細に出ない扱いになります。
          </li>
          <li>
            <strong>プレビュー用URL</strong>: 確認用に、<strong>未公開（下書き）の記事</strong>も一覧や詳細に含まれることがあります。公開前の内容確認に使い、一般公開の見え方は本番URLでも必ず確認してください。
          </li>
        </ul>

        <h3 id="preview-url-cache">キャッシュの仕組み</h3>
        <p>
          「更新したのにすぐ反映されない」原因は、大きく<strong>サーバー内のデータキャッシュ</strong>と<strong>CDN／ブラウザのHTTPキャッシュ</strong>に分けて考えられます。
        </p>
        <ul>
          <li>
            <strong>サーバー内メモリキャッシュ</strong>: 記事本文・一覧・サイト情報などを高速化するため、サーバー上に短時間キャッシュされます。ここでは<strong>プレビュー用のアクセス</strong>と<strong>本番ドメインのアクセス</strong>で<strong>別々のキャッシュキー</strong>が使われるため、プレビューで見た内容と本番で見た内容が混ざることはありません。保持時間はデータの種類により<strong>数分〜30分程度</strong>が目安です（環境・負荷で前後します）。
          </li>
          <li>
            <strong>CDN・エッジ・ブラウザ</strong>: 配信インフラの設定により、HTML に <code>Cache-Control</code> などが付き、<strong>数十秒〜数分</strong>は古いページが返ることがあります。記事やトップを更新した直後に変化が見えない場合は、少し時間をおいてから再読み込みするか、ブラウザの強制再読み込み（キャッシュ無視）を試してください。
          </li>
          <li>
            <strong>運用上の整理</strong>: 下書きやデザインの確認はプレビューURL、検索に載ったときの見え方や計測タグの動作は本番URL、という使い分けがわかりやすいです。挙動が異なるのはバグではなく、上記の<strong>公開条件・検索インデックス・キャッシュ層の違い</strong>によるものです。
          </li>
        </ul>
      </section>


async function run() {
  for (const page of pages) {
    // Check if page already exists
    const existing = await db.collection('pages')
      .where('mediaId', '==', MEDIA_ID)
      .where('slug', '==', page.slug)
      .get();
    
    if (existing.size > 0) {
      // Update existing page
      const doc = existing.docs[0];
      const blocks = makeBlocks(page.html);
      await db.collection('pages').doc(doc.id).update({
        title: page.title,
        blocks,
        updatedAt: admin.firestore.FieldValue.serverTimestamp(),
      });
      console.log(`Updated existing page: ${page.slug} (${doc.id})`);
    } else {
      // Create new page
      const blocks = makeBlocks(page.html);
      const docRef = await db.collection('pages').add({
        mediaId: MEDIA_ID,
        slug: page.slug,
        title: page.title,
        blocks,
        layoutMode: 'blank',
        isPublished: true,
        order: 0,
        createdAt: admin.firestore.FieldValue.serverTimestamp(),
        updatedAt: admin.firestore.FieldValue.serverTimestamp(),
      });
      console.log(`Created new page: ${page.slug} (${docRef.id})`);
    }
  }
  
  console.log('\nAll 4 policy pages created/updated!');
}

run().catch(console.error);
